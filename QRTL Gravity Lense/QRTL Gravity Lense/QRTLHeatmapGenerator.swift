 The effective gravitational potential is obtained by integrating the gravitational influence of this field through space. The ordinary gravitational contribution for the extended Gaussian cluster can be calculated from the total cluster mass and the Gaussian density distribution rather than treating the cluster as a mathematical point. The QRTL contribution can then either be interpreted as the mechanism producing the effective gravitational potential or, if the model explicitly requires it, as an additional contribution to the conventional gravitational potential. This distinction is important because the same gravitational effect should not be counted twice. The resulting effective potential becomes the central field from which the spacetime geometry is constructed.

 The effective potential determines the local spacetime metric. In regions where the gravitational field is weak, the time component of the metric is reduced according to the gravitational potential, while the spatial components are modified correspondingly. This means that the gravitational field does not merely bend a two-dimensional surface. It changes the relationship between time and space at every point surrounding the globular cluster. A clock located deeper inside the gravitational field experiences a different relationship between proper time and coordinate time than a clock farther away. The same metric also determines how the paths available to photons change as they travel through the field.

 The metric is then differentiated to calculate the Christoffel connection coefficients. These coefficients describe how the coordinate directions change from one location to another in the curved spacetime. The Christoffel field is then differentiated again to obtain the Riemann curvature tensor. The Riemann tensor contains the directional information describing how spacetime curves around the globular cluster. From this tensor, a curvature magnitude can be calculated. This curvature magnitude provides a single spatial measure of how strongly the local spacetime geometry is being distorted. It is this tensor-derived curvature, rather than simply the mass density, that should control the shape of the visual gravitational surface.

